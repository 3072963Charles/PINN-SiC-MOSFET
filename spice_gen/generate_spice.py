def generate_veriloga_model(params: Dict[str, float],
                            output_path: str = None) -> str:
    """
    Generate a Verilog-A compact model (optional, for Spectre/ADS users).

    Args:
        params: Physical parameter dictionary
        output_path: Output file path

    Returns:
        Verilog-A model string
    """
    va_template = """// Verilog-A for 4H-SiC Power MOSFET
// Generated from PINN Parameter Extraction
// Date: {date}

`include "disciplines.vams"
`include "constants.vams"

module SiC_MOSFET_PINN(d, g, s);
    inout d, g, s;
    electrical d, g, s;
    electrical d_int, s_int;

    // --- Physical Parameters (from PINN extraction) ---
    parameter real VTO = {VTO};
    parameter real KP  = {KP};
    parameter real THETA = {THETA};
    parameter real U0 = {U0};
    parameter real GAMMA = {GAMMA};
    parameter real PHI = {PHI};
    parameter real VMAX = {VMAX};
    parameter real KAPPA = {KAPPA};
    parameter real LAMBDA = {LAMBDA};
    parameter real TOX = {TOX};
    parameter real NFS = {NFS};

    parameter real COX = {COX};
    parameter real WEFF = {WEFF};
    parameter real LEFF = {LEFF};

    real Vgs, Vds, Vth, mu_eff;
    real beta, Vdsat, Ids_lin, Ids_sat, Ids;

    analog begin
        Vgs = V(g, s_int);
        Vds = V(d_int, s_int);

        // Threshold voltage (with DIBL)
        Vth = VTO + GAMMA * (sqrt(PHI) - sqrt(PHI));

        // Effective mobility
        mu_eff = U0 / (1.0 + THETA * (Vgs - Vth));

        // Transconductance
        beta = mu_eff * COX * WEFF / LEFF;

        // Drain current (Level-3 model)
        if (Vgs <= Vth) begin
            // Subthreshold
            Ids = 0.0;
        end else if (Vds < (Vgs - Vth) / (1.0)) begin
            // Linear region
            Ids = beta * (Vgs - Vth - 0.5 * Vds) * Vds * (1.0 + LAMBDA * Vds);
        end else begin
            // Saturation region
            Vdsat = (Vgs - Vth) / (1.0 + KAPPA);
            Ids = beta / (2.0 * (1.0 + KAPPA)) * (Vgs - Vth) * (Vgs - Vth)
                  * (1.0 + LAMBDA * Vds);
        end

        // Output
        I(d_int, s_int) <+ Ids;
    end
endmodule
"""

    va_content = va_template.format(
        date=datetime.now().strftime('%Y-%m-%d'),
        VTO=params.get('VTO', 5.0),
        KP=params.get('KP', 0.1),
        THETA=params.get('THETA', 0.05),
        U0=params.get('U0', 30.0),
        GAMMA=params.get('GAMMA', 2.0),
        PHI=params.get('PHI', 0.65),
        VMAX=params.get('VMAX', 2e7),
        KAPPA=params.get('KAPPA', 0.5),
        LAMBDA=params.get('LAMBDA', 0.001),
        TOX=params.get('TOX', 5e-8),
        NFS=params.get('NFS', 5e11),
        COX=params.get('COX', EPS_OX/5e-8),
        WEFF=5.2e-6,
        LEFF=1.0e-6,
    )

    if output_path:
        with open(output_path, 'w') as f:
            f.write(va_content)

    return va_content
