"""
SPICE Model Generator
======================
Converts PINN-extracted physical parameters into standard SPICE Level-3
.MODEL statements and .SUBCKT netlists.

The generated model can be directly used in:
  - LTspice / ngspice / PSpice / HSPICE
  - Circuit simulations (Buck, Boost, inverter, etc.)

Inherits the subcircuit template structure from previous work (test_D1.lib)
but replaces the behavioral bswitch with a standard .MODEL NMOS LEVEL=3.
"""

