def generate_spice_model(params: Dict[str, float],
                         output_path: str = None,
                         include_validation_circuit: bool = False,
                         ) -> str:
    """
    Generate a complete SPICE subcircuit model from PINN-extracted parameters.

    Args:
        params: Dictionary of physical parameters from PINN extraction
        output_path: If provided, write the model to this file
        include_validation_circuit: If True, append a validation testbench

    Returns:
        SPICE netlist string
    """
    # Build parameter comment block
    param_lines = []
    param_descriptions = {
        'VTO': 'Zero-bias threshold voltage',
        'KP': 'Transconductance parameter',
        'THETA': 'Mobility degradation coefficient',
        'U0': 'Low-field surface mobility',
        'NFS': 'Fast surface state density',
        'GAMMA': 'Body effect coefficient',
        'PHI': 'Surface potential 2*phi_p',
        'VMAX': 'Carrier saturation velocity',
        'KAPPA': 'Saturation field factor',
        'LAMBDA': 'Channel length modulation',
        'R_JFET0': 'JFET zero-bias resistance',
        'KAPPA_VT': 'VTH temperature coefficient',
        'ALPHA_MU': 'Mobility temperature exponent',
    }

    for key, desc in param_descriptions.items():
        if key in params:
            param_lines.append(f"*   {key:12s} = {params[key]:.6e}  ({desc})")

    # Map params to template variables
    template_vars = {
        'date': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
        'param_comment': '\n'.join(param_lines),

        # Level-3 model parameters
        'VTO': params.get('VTO', 5.0),
        'KP': params.get('KP', 0.1),
        'THETA': params.get('THETA', 0.05),
        'U0': params.get('U0', 30.0),
        'NFS': params.get('NFS', 5e11),
        'GAMMA': params.get('GAMMA', 2.0),
        'PHI': params.get('PHI', 0.65),
        'VMAX': params.get('VMAX', 2e7),
        'KAPPA': params.get('KAPPA', 0.5),
        'LAMBDA': params.get('LAMBDA', 0.001),
        'TOX': params.get('TOX', 5e-8),

        # Subcircuit parameters
        'RS_VAL': params.get('RS_VAL', 0.01),
        'RJFET0_VAL': params.get('R_JFET0', 0.1),

        # Temperature parameters
        'KAPPA_VT': params.get('KAPPA_VT', -0.005),
        'ALPHA_MU': params.get('ALPHA_MU', 2.5),
    }

    # Generate main netlist
    netlist = SPICE_SUBCKT_TEMPLATE.format(**template_vars)

    # Append validation testbench if requested
    if include_validation_circuit:
        netlist += VALIDATION_TESTBENCH

    # Write to file if path provided
    if output_path:
        os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)
        with open(output_path, 'w') as f:
            f.write(netlist)
        print(f"SPICE model written to: {output_path}")

    return netlist


